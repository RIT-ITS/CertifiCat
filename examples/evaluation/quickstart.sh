#!/usr/bin/env bash
# Self-contained CertifiCat evaluation environment.
#
# On the first run this script writes config.yaml next to itself (or to the
# current directory when piped into bash from curl) with a random
# secret key, Redis password and admin password, and a freshly generated
# self-signed CA for the local finalizer. CertifiCat uses SQLite for storage and
# runs the web interface and task runner in a single container, alongside a
# dedicated Redis container on a private Docker network.
#
# If config.yaml already exists, setup is skipped and the containers are
# (re)started with the existing configuration.
#
# Requirements: docker (or a compatible CLI set in $DOCKER) and openssl.
#
# Environment overrides:
#   CERTIFICAT_IMAGE  CertifiCat image (default: ghcr.io/rit-its/certificat:latest)
#   REDIS_IMAGE       Redis image (default: redis:7.2.4)
#   CERTIFICAT_PORT       Host port for the web interface (default: 8000, first run only)
#   CERTIFICAT_PULL       Pull CERTIFICAT_IMAGE before starting (default: true)
#   CERTIFICAT_EVAL_NAME  Prefix for the containers, network and volume
#                         (default: certificat-eval)
#   DOCKER                Container CLI (default: docker)
#
# To reset everything, run (with the default name):
#   docker rm -f certificat-eval certificat-eval-redis
#   docker volume rm certificat-eval-data
#   docker network rm certificat-eval
#   rm config.yaml

set -euo pipefail

CERTIFICAT_IMAGE="${CERTIFICAT_IMAGE:-ghcr.io/rit-its/certificat:latest}"
REDIS_IMAGE="${REDIS_IMAGE:-redis:7.2.4}"
CERTIFICAT_PORT="${CERTIFICAT_PORT:-8000}"
CERTIFICAT_PULL="${CERTIFICAT_PULL:-true}"
CERTIFICAT_EVAL_NAME="${CERTIFICAT_EVAL_NAME:-certificat-eval}"
DOCKER="${DOCKER:-docker}"

NETWORK="${CERTIFICAT_EVAL_NAME}"
REDIS_CONTAINER="${CERTIFICAT_EVAL_NAME}-redis"
CERTIFICAT_CONTAINER="${CERTIFICAT_EVAL_NAME}"
DATA_VOLUME="${CERTIFICAT_EVAL_NAME}-data"
DATA_DIR="/var/lib/certificat"

# When the script is piped into bash (curl ... | bash) there is no script file,
# so BASH_SOURCE is empty and config.yaml goes in the current directory instead.
if [ -n "${BASH_SOURCE[0]:-}" ] && [ -f "${BASH_SOURCE[0]}" ]; then
  HERE=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)
else
  HERE=$(pwd)
fi
CONFIG="${HERE}/config.yaml"

log() {
  echo "$(date "+%Y/%m/%d %H:%M:%S") $*"
}

die() {
  log "ERROR $*" >&2
  exit 1
}

require() {
  command -v "$1" &>/dev/null || die "'$1' is required but was not found on PATH."
}

container_exists() {
  "${DOCKER}" container inspect "$1" &>/dev/null
}

# Indent every line of stdin by six spaces so PEM blocks nest under a YAML key.
indent() {
  sed 's/^/      /'
}

generate_config() {
  require openssl

  log "INFO No config.yaml found, generating a new one at ${CONFIG}"

  local workdir
  workdir=$(mktemp -d)
  # shellcheck disable=SC2064
  trap "rm -rf '${workdir}'" RETURN

  log "INFO Generating a self-signed CA for the local finalizer"
  openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 3650 \
    -subj "/CN=CertifiCat Evaluation CA" \
    -addext "basicConstraints=critical,CA:TRUE" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -keyout "${workdir}/ca.key" -out "${workdir}/ca.crt" 2>/dev/null \
    || die "Failed to generate the CA certificate."

  local secret_key redis_password admin_password
  secret_key=$(openssl rand -hex 32)
  redis_password=$(openssl rand -hex 16)
  admin_password=$(openssl rand -hex 8)

  # Write to a temporary file first so a failure never leaves a partial config
  # behind, which would make the next run skip setup.
  cat >"${workdir}/config.yaml" <<EOF
# Generated by quickstart.sh on $(date "+%Y-%m-%d %H:%M:%S").
# This configuration is for evaluation only. Do not use it in production.
certificat:
  secret_key: "${secret_key}"
  time_zone: "America/New_York"
  url_root: "http://localhost:${CERTIFICAT_PORT}"
  # The web interface, the task runner's worker threads and the task statistics
  # all write to this one file. WAL mode, immediate transactions and a generous
  # busy timeout make writers wait for each other instead of failing with
  # "database is locked".
  db:
    type: "sqlite"
    name: "${DATA_DIR}/certificat.sqlite3"
    options:
      transaction_mode: IMMEDIATE
      timeout: 20
      init_command: "PRAGMA journal_mode=WAL; PRAGMA synchronous=NORMAL"
  redis:
    host: "${REDIS_CONTAINER}"
    password: "${redis_password}"
    port: 6379
  # Task statistics have to live in the main database: the web interface and
  # periodic cleanup read them through Django, which only knows that database.
  task_queue:
    stats_database: "sqlite:///${DATA_DIR}/certificat.sqlite3?timeout=20"
  logging:
    certificat_level: DEBUG
    acmev2_level: DEBUG
  authentication:
    type: local
    admin:
      username: admin
      password: "${admin_password}"
      email: noreply@localhost
  finalizer:
    type: local
    key: |
$(indent <"${workdir}/ca.key")
    cert: |
$(indent <"${workdir}/ca.crt")
EOF

  # The file is world-readable on purpose: the web interface and task runner run
  # as an unprivileged user inside the container and need to read it.
  chmod 644 "${workdir}/config.yaml"
  mv "${workdir}/config.yaml" "${CONFIG}"
}

# Read a value from config.yaml with the yq binary shipped in the CertifiCat image.
config_value() {
  "${DOCKER}" run --rm --entrypoint yq \
    -v "${CONFIG}:/etc/certificat/config.yaml:ro,z" \
    "${CERTIFICAT_IMAGE}" -r "$1" /etc/certificat/config.yaml
}

# Everything runs from main, which is only called on the last line. When the
# script is piped from curl, bash executes it as it downloads, so a dropped
# connection would otherwise run a truncated script.
main() {
  require "${DOCKER}"
  require curl

  if [ -f "${CONFIG}" ]; then
    log "INFO Found existing ${CONFIG}, skipping setup and starting CertifiCat"
    FRESH_CONFIG=false
  else
    generate_config
    FRESH_CONFIG=true
  fi

  if [ "${CERTIFICAT_PULL}" = true ]; then
    log "INFO Pulling ${CERTIFICAT_IMAGE}"
    "${DOCKER}" pull "${CERTIFICAT_IMAGE}" >/dev/null \
      || log "WARN Could not pull ${CERTIFICAT_IMAGE}, using the local copy if there is one"
  fi

  REDIS_PASSWORD=$(config_value '.certificat.redis.password')
  URL_ROOT=$(config_value '.certificat.url_root')
  ADMIN_USERNAME=$(config_value '.certificat.authentication.admin.username')
  ADMIN_PASSWORD=$(config_value '.certificat.authentication.admin.password')
  [ -n "${REDIS_PASSWORD}" ] && [ "${REDIS_PASSWORD}" != "null" ] \
    || die "certificat.redis.password is missing from ${CONFIG}."

  # The published port has to match the port in url_root, otherwise ACME clients
  # are handed URLs they can't reach.
  HOST_PORT=$(sed -nE 's#^https?://[^/:]+:([0-9]+).*#\1#p' <<<"${URL_ROOT}")
  HOST_PORT="${HOST_PORT:-80}"

  "${DOCKER}" network inspect "${NETWORK}" &>/dev/null \
    || "${DOCKER}" network create "${NETWORK}" >/dev/null

  # Redis only holds the cache and task queue, so it's recreated on every run to
  # pick up the password from config.yaml.
  if container_exists "${REDIS_CONTAINER}"; then
    "${DOCKER}" rm -f "${REDIS_CONTAINER}" >/dev/null
  fi
  log "INFO Starting Redis (${REDIS_CONTAINER})"
  "${DOCKER}" run -d \
    --name "${REDIS_CONTAINER}" \
    --network "${NETWORK}" \
    --restart unless-stopped \
    "${REDIS_IMAGE}" \
    redis-server --save "" --appendonly no --requirepass "${REDIS_PASSWORD}" >/dev/null

  if container_exists "${CERTIFICAT_CONTAINER}"; then
    "${DOCKER}" rm -f "${CERTIFICAT_CONTAINER}" >/dev/null
  fi

  # The web interface and task runner run as the unprivileged certificat user,
  # while migrations run as root during startup. Create the SQLite database ahead
  # of time and hand the data directory to certificat so both can write to it.
  log "INFO Starting CertifiCat (${CERTIFICAT_CONTAINER}) on port ${HOST_PORT}"
  "${DOCKER}" run -d \
    --name "${CERTIFICAT_CONTAINER}" \
    --network "${NETWORK}" \
    --restart unless-stopped \
    --publish "${HOST_PORT}:80" \
    --add-host "host.docker.internal:host-gateway" \
    --volume "${CONFIG}:/etc/certificat/config.yaml:ro,z" \
    --volume "${DATA_VOLUME}:${DATA_DIR}" \
    --env CERTIFICAT__CONFIG=/etc/certificat/config.yaml \
    --entrypoint /bin/bash \
    "${CERTIFICAT_IMAGE}" \
    -c "mkdir -p ${DATA_DIR} \
        && touch ${DATA_DIR}/certificat.sqlite3 \
        && chown -R certificat ${DATA_DIR} \
        && exec /srv/www/entrypoint.sh start" >/dev/null

  log "INFO Waiting for CertifiCat to become ready"
  # First startup runs migrations and collects static files, which can take a
  # couple of minutes.
  for _ in $(seq 1 150); do
    # A container that exited or is crash-looping won't come up on its own.
    if [ "$("${DOCKER}" container inspect -f '{{.State.Status}}/{{.RestartCount}}' "${CERTIFICAT_CONTAINER}" 2>/dev/null)" != "running/0" ]; then
      echo
      "${DOCKER}" logs --tail 50 "${CERTIFICAT_CONTAINER}" >&2 || true
      die "CertifiCat exited during startup, see the logs above."
    fi
    if curl -fsS -o /dev/null "http://localhost:${HOST_PORT}/directory" 2>/dev/null; then
      READY=true
      break
    fi
    echo -n "."
    sleep 2
  done
  echo

  if [ "${READY:-false}" != true ]; then
    "${DOCKER}" logs --tail 30 "${CERTIFICAT_CONTAINER}" >&2 || true
    log "WARN CertifiCat isn't answering yet, see the logs above. Follow its progress with: ${DOCKER} logs -f ${CERTIFICAT_CONTAINER}"
  fi

  cat <<EOF

CertifiCat is running at ${URL_ROOT}
  Web login:       ${ADMIN_USERNAME} / ${ADMIN_PASSWORD}
  ACME directory:  ${URL_ROOT%/}/directory
  Configuration:   ${CONFIG}$( [ "${FRESH_CONFIG}" = true ] && echo " (new)" )

Log in, create an account binding, then request a certificate, for example:
  certbot certonly --standalone --server "${URL_ROOT%/}/directory" \\
    -d host.docker.internal

Logs:  ${DOCKER} logs -f ${CERTIFICAT_CONTAINER}
Stop:  ${DOCKER} stop ${CERTIFICAT_CONTAINER} ${REDIS_CONTAINER}
EOF
}

main "$@"
